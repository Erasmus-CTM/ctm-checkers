"""Writes src/ctm_checkers/stack/stack_data.py, the data of STACK's own input
rules that ctm_checkers.stack.student_input applies to students' answers
(S-13), from a STACK checkout (the commit of native-stack.yml).

    python tools/stack_native/stack_input_data.py --stack-source STACK          # write it
    python tools/stack_native/stack_input_data.py --stack-source STACK --check  # it is current (CI)

From STACK's stack/cas/security-map.json (cassecurity.class.php):
the identifiers a student may read (security "s" as a variable or a
constant), those nobody may read ("f", keywords and operators), those a
student may call, the function names of up to two letters (which a student
may not use as variables), the trigonometric functions, the globally
forbidden variables, and the spellings of each identifier by its lower case
(for STACK's "Input is case sensitive" messages: the identifiers of each kind); from
stack/maximaparser/unicode/symbols-stack.json and letters-stack.json: the
characters STACK replaces before it parses an answer, in its order.

Part of ctm-checkers, AGPL-3.0-or-later. The data it writes is STACK's
(GPL-3.0-or-later), used here under the AGPL's section 13.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'src' / 'ctm_checkers' / 'stack' / 'stack_data.py'


def commit_of(source):
    result = subprocess.run(['git', '-C', str(source), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else 'unknown'


def literal(value, indent='    '):
    """A Python literal with one entry per line (stable diffs)."""
    if isinstance(value, (list, tuple)):
        return '(\n' + ''.join(f'{indent}{item!r},\n' for item in value) + ')'
    if isinstance(value, dict):
        return '{\n' + ''.join(f'{indent}{key!r}: {item!r},\n' for key, item in value.items()) + '}'
    raise TypeError(value)


def generate(source):
    security = json.loads((source / 'stack' / 'cas' / 'security-map.json').read_text(encoding='utf-8'))
    unicode = source / 'stack' / 'maximaparser' / 'unicode'
    symbols = json.loads((unicode / 'symbols-stack.json').read_text(encoding='utf-8'))
    letters = json.loads((unicode / 'letters-stack.json').read_text(encoding='utf-8'))

    def level(entry):   # cassecurity::is_allowed_to_read: a constant's security overrides a variable's
        found = '-'
        if 'variable' in entry:
            found = entry['variable']
        if 'constant' in entry:
            found = entry['constant']
        return found

    readable = sorted(k for k, v in security.items() if level(v) == 's')
    unreadable = sorted(k for k, v in security.items() if level(v) == 'f'
                        or (('keyword' in v or 'operator' in v) and 'specialallowvariable' not in v))
    callable_ = sorted(k for k, v in security.items() if v.get('function') == 's')
    short_functions = sorted(k for k, v in security.items() if 'function' in v and len(k) <= 2)
    trig = sorted(k for k, v in security.items() if v.get('trigfun'))
    globally_forbidden = sorted(k for k, v in security.items() if v.get('globalyforbiddenvariable'))
    # get_case_variants: the identifiers of a kind, in the map's order (their spellings by lower case).
    variables = [k for k, v in security.items() if 'variable' in v or 'constant' in v]
    functions = [k for k, v in security.items() if 'function' in v]
    replacements = list(symbols.items()) + list(letters.items())
    commit = commit_of(source)
    parts = [
        '"""STACK\'s data for its input rules (S-13): generated by',
        'tools/stack_native/stack_input_data.py from STACK ' + commit[:12] + ' (stack/cas/security-map.json,',
        'stack/maximaparser/unicode/symbols-stack.json and letters-stack.json); do not edit.',
        '',
        'This data is STACK\'s (https://github.com/maths/moodle-qtype_stack, GPL-3.0-or-later),',
        'combined with ctm-checkers (AGPL-3.0-or-later) under section 13 of the GNU AGPL."""',
        '',
        f'STACK_COMMIT = {commit!r}',
        '',
        '# Identifiers a student may use as variables or constants (security "s").',
        f'READABLE = frozenset({literal(readable)})',
        '',
        '# Identifiers nobody may use as variables (security "f"; keywords and operators).',
        f'UNREADABLE = frozenset({literal(unreadable)})',
        '',
        '# Functions a student may call (security "s").',
        f'CALLABLE = frozenset({literal(callable_)})',
        '',
        '# Function names of one or two letters: not variables a student may use.',
        f'SHORT_FUNCTIONS = frozenset({literal(short_functions)})',
        '',
        '# Trigonometric functions (STACK\'s feature "trigfun").',
        f'TRIG_FUNCTIONS = frozenset({literal(trig)})',
        '',
        '# Variables nobody may use ("globalyforbiddenvariable").',
        f'GLOBALLY_FORBIDDEN = frozenset({literal(globally_forbidden)})',
        '',
        '# The variables and constants, and the functions, in the map\'s order (get_case_variants).',
        f'VARIABLES = {literal(variables)}',
        f'FUNCTIONS = {literal(functions)}',
        '',
        '# Characters STACK replaces in an answer before it parses it, in its order (symbols, then letters).',
        f'REPLACEMENTS = {literal(replacements)}',
        '',
    ]
    return '\n'.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--stack-source', type=Path, required=True, help='STACK checkout (native-stack.yml: .stack-upstream-reference)')
    parser.add_argument('--check', action='store_true', help='fail when the committed module differs')
    options = parser.parse_args()
    text = generate(options.stack_source.resolve())
    if options.check:
        current = TARGET.read_text(encoding='utf-8')
        if current != text:
            print(f'{TARGET.relative_to(ROOT)} is not what STACK at {commit_of(options.stack_source)} gives: '
                  'run python tools/stack_native/stack_input_data.py --stack-source …', file=sys.stderr)
            return 1
        print(f'{TARGET.relative_to(ROOT)} is current.')
        return 0
    TARGET.write_text(text, encoding='utf-8')
    print(f'Wrote {TARGET.relative_to(ROOT)} ({len(text.encode("utf-8"))} bytes).')
    return 0


if __name__ == '__main__':
    sys.exit(main())
